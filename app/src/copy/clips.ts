/** The key of `USE` for a clip, from where its result goes. */
export function usedFor(store: { to: string; field?: string; keys?: readonly string[] }, code: string): string {
  if (store.to === "screen") return USE[store.field ?? "note"];
  if (store.to === "browser") return USE.browser;
  if (store.to === "note") return code === "M24" ? USE.sighting : USE.note;
  return USE[store.keys?.[0] ?? ""] ?? USE.own;
}

/* ───────────── a stored value in words ───────────── */

const END = {
  finer: (v: string) => `${v} or finer`,
  coarser: (v: string) => `coarser than ${v}`,
  more: (v: string) => `${v} or more`,
};

const DOTS: Record<number, string> = { 0: "Four dots seen", 1: "Five dots seen", 2: "Two or three dots seen" };

/** A stored value as a member reads it, by key. `note` says when it sits at an end of what the clip could show. */
export function reading(key: string, unit: string, value: number, note?: string | null): string {
  const v = n1(value), abs = n1(Math.abs(value));
  if (unit === "logMAR") return acuityText({ ...blankEye(), va: value, note: note === "floor" || note === "worse" ? note : "" });
  if (unit === "logCS") return note === "worse" ? "Not seen at the strongest step" : `${(100 * Math.pow(10, -value)).toFixed(1)}% contrast`;
  if (unit === "log_ratio") return `${percent(Math.pow(10, -Math.abs(value)))} for the stronger eye`;
  if (unit === "arcsec") { const s = `${v} arc seconds`; return note === "floor" ? END.finer(s) : note === "worse" ? END.coarser(s) : s; }
  if (key === "alignment_h") return value === 0 ? "No drift found" : `${abs} prism dioptres, turned ${value > 0 ? "in" : "out"}`;
  if (key === "alignment_v") return value === 0 ? "Level" : `${abs} prism dioptres, ${value > 0 ? "right" : "left"} eye higher`;
  if (key === "alignment_shift") return value === 0 ? "No shift" : `${abs} prism dioptres toward turning ${value > 0 ? "in" : "out"}`;
  if (key === "fixation_offset") return value === 0 ? "On target" : `${abs} minutes of arc, toward turning ${value > 0 ? "in" : "out"}`;
  if (unit === "prism_dioptre") { const s = `${v} prism dioptres`; return note === "floor" ? END.more(s) : s; }
  if (key === "suppression") return DOTS[value] ?? v;
  if (key === "symptoms") return `${v} of 60`;
  if (key === "screen_strain") return `${v} of 40`;
  if (key === "dry_eye") return `${v} of 24`;
  if (key === "suppression_map") return value === 0 ? "No place missed" : `${v} of 16 places missed`;
  if (key === "field_missed") return value === 0 ? "No place missed" : `${v} of 24 places missed`;
  if (key === "grid_marks") return value === 0 ? "No squares marked" : `${v} ${plural(value, "square", "squares")} marked`;
  if (key === "fusion_hold") return note === "floor" ? `${v} seconds: the whole time` : `${v} seconds`;
  if (key === "vergence_flips") return `${v} full flips a minute`;
  if (key === "blink_rate") return `${v} blinks a minute`;
  if (unit === "seconds") return `${v} seconds`;
  if (unit === "cm") return `${v} cm`;
  if (unit === "percent") return key === "tracking" ? `${v}% of the time` : note === "floor" ? `${v}% or finer` : note === "worse" ? `not told apart at ${v}%, the largest ripple shown` : `${v}%`;
  if (unit === "words_per_min") return `${v} words a minute`;
  return v;
}

