const zone = "Asia/Kolkata";
/** A date as staff read it, for example 4 Oct 2026. */
export const day = (d: Date) => new Intl.DateTimeFormat("en-IN", { dateStyle: "medium", timeZone: zone }).format(d);
/** A date with the time, for example 4 Oct 2026, 9:12 am. */
export const dayTime = (d: Date) => new Intl.DateTimeFormat("en-IN", { dateStyle: "medium", timeStyle: "short", timeZone: zone }).format(d);
/** Whole days since a moment. */
export const daysSince = (d: Date, now = new Date()) => Math.max(0, Math.floor((now.getTime() - d.getTime()) / 86_400_000));
export const ageText = (d: Date) => { const n = daysSince(d); return n === 0 ? "Today" : n === 1 ? "1 day" : `${n} days`; };
export const dollars = (n: number) => `$${n.toFixed(2)}`;
const many = (n: number, one: string, more: string) => `${n} ${n === 1 ? one : more}`;

